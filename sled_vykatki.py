# -*- coding: utf-8 -*-
"""След выкатки — строкой в федеральный журнал сервера, сразу и без участия человека.

🔴 04.09.2026, слово владельца (#2624): «федеральный журнал по ораклу подробный со всей
историей не забывай вести, каждое изменение вписывая туда, не затирая что было в журнале».

ПОЧЕМУ ЭТО ДЕЛАЕТ СКРИПТ, А НЕ Я. Закон о журнале сервера (З-94) был записан 03.09, а за
следующие сутки в журнал не легло ни строки — при восьми выкатках и трёх изменениях состава.
Каждое изменение я записывал в другие журналы и считал, что след оставлен. Значит дело не в
намерении: то, что делается руками, забывается. То, что делает выкатка, забыть нельзя.

Пишет ДОПИСЫВАНИЕМ в конец файла — прежние записи не трогает.

Запуск (из vykatka.sh, последним шагом):
    python3 sled_vykatki.py <коммит> <снимок из /api/health>
"""
import io
import os
import subprocess
import sys
import time

ЖУРНАЛ_ЛОКАЛЬНО = '/opt/muslimoon/ЖУРНАЛ_ВЫКАТОК.md'


def строка(коммит, снимок, сообщение):
    return ('- **%s МСК** · выкатка `%s` · снимок прода `%s` · %s\n'
            % (time.strftime('%d.%m.%Y %H:%M', time.gmtime(time.time() + 3 * 3600)),
               коммит[:12], снимок, сообщение[:200].replace('\n', ' ')))


def главное():
    коммит = sys.argv[1] if len(sys.argv) > 1 else '?'
    снимок = sys.argv[2] if len(sys.argv) > 2 else '?'
    # заголовок коммита — он и есть «что изменилось», писать его отдельно не нужно
    try:
        сообщение = subprocess.run(
            ['git', '-C', '/opt/muslimoon', 'log', '-1', '--pretty=%s', коммит],
            capture_output=True, encoding='utf-8', errors='replace', timeout=30).stdout.strip()
    except Exception:
        сообщение = ''
    if not сообщение:
        сообщение = '(заголовок коммита не прочёлся)'

    шапка = ('# 🚀 ЖУРНАЛ ВЫКАТОК СЕРВЕРА (пишется сам)\n\n'
             'Каждая выкатка `vykatka.sh` оставляет здесь строку: когда, какой коммит, какой\n'
             'снимок прода после неё и что менялось. Ведётся скриптом `sled_vykatki.py`,\n'
             'потому что вручную это забывается (см. З-94, запись №15 федерального журнала).\n\n'
             '⛔ Строки не удалять и не переписывать: журнал только дописывается.\n\n')
    было = os.path.exists(ЖУРНАЛ_ЛОКАЛЬНО)
    with io.open(ЖУРНАЛ_ЛОКАЛЬНО, 'a', encoding='utf-8', newline='\n') as ф:
        if not было:
            ф.write(шапка)
        ф.write(строка(коммит, снимок, сообщение))
    print('   след выкатки записан в %s' % os.path.basename(ЖУРНАЛ_ЛОКАЛЬНО))
    return 0


if __name__ == '__main__':
    sys.exit(главное())
