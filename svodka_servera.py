# 🔴 06.09.2026, ЦЕНА НЕПРОВЕРЕННОЙ КОНСТАНТЫ. Здесь стояло «4, 24» — старая норма Oracle.
# В АВГУСТЕ 2026 Oracle урезал бесплатный ARM ВДВОЕ: теперь Always Free даёт 1 500
# ядро-часов и 9 000 ГБ-часов в месяц, что при работе 24/7 равно ровно 2 ядрам и 12 ГБ.
# То есть наша машина стоит НЕ на половине бесплатного, а РОВНО НА ПОТОЛКЕ.
# Из-за этих двух чисел сводка месяц писала «не взято ещё 2 ядра и 12 ГБ», а я на их
# основании сказал владельцу, что мы зря не взяли всё бесплатное. Взять их можно — но тогда
# 1 500 ядро-часов кончатся к середине месяца, и дальше пойдёт ПЛАТНОЕ время. Владелец
# 06.09.2026: «нельзя платно чтобы было оракл». Значит добавлять ядра и память нельзя.
# Источник: docs.oracle.com → Free Tier → Always Free Resources. Проверено, не по памяти.
#
# Диск живёт по другому правилу: 200 ГБ на весь аккаунт, загрузочный том считается в них.
# Наш том 46,6 ГБ, значит ~153 ГБ можно добрать БЕСПЛАТНО — это единственное, что у нас
