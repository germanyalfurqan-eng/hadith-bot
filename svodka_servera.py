БАЗА = 'https://130.61.182.191.sslip.io'
СЕКРЕТ = '/opt/muslimoon/.backup_secret'
СЕТЬ = '/sys/class/net/enp0s6/statistics'

# Лимиты Always Free — то, с чем сравниваем. Это НА ВЕСЬ АККАУНТ, а не на одну машину.
ЛИМ_ЯДЕР, ЛИМ_ПАМЯТИ_ГБ, ЛИМ_ДИСКА_ГБ, ЛИМ_ТРАФИКА_ТБ = 4, 24, 200, 10


def _чис(путь):
    try:
        return int(io.open(путь).read().strip())
    except Exception:
        return 0


def собрать():
    ядер = os.cpu_count() or 0
    mem = {}
    for с in io.open('/proc/meminfo'):
        ч = с.split(':')
        if len(ч) == 2:
            mem[ч[0]] = int(ч[1].strip().split()[0])
    всего_гб = mem.get('MemTotal', 0) / 1048576.0
    свободно_гб = mem.get('MemAvailable', 0) / 1048576.0
    ст = os.statvfs('/')
    диск_всего = ст.f_blocks * ст.f_frsize / 1073741824.0
    диск_свободно = ст.f_bavail * ст.f_frsize / 1073741824.0
    tx = _чис(СЕТЬ + '/tx_bytes') / 1073741824.0
    аптайм = float(io.open('/proc/uptime').read().split()[0])
    часов = аптайм / 3600.0
    в_сутки = tx / (часов / 24.0) if часов > 1 else tx
    нагрузка = os.getloadavg()[1]
    return {'ядер': ядер, 'память_всего': всего_гб, 'память_свободно': свободно_гб,
            'диск_всего': диск_всего, 'диск_свободно': диск_свободно,
            'отдано_гб': tx, 'часов': часов, 'в_сутки_гб': в_сутки,
            'в_месяц_гб': в_сутки * 30, 'нагрузка': нагрузка}


def _срок(часов):
    """«38 часов» человеку ничего не говорит, «полтора дня» — говорит."""
    if часов < 48:
        return '%.0f часов' % часов
    д = часов / 24.0
    return '%.0f суток' % д if д >= 2 else '%.1f суток' % д


def словами(д):
    """Сводка тремя блоками: что за машина, как она себя чувствует, сколько раздала.

    Порядок не случаен. Сперва — из чего мы вообще исходим (иначе любое число не с чем
    сравнить), потом — самочувствие прямо сейчас, и только потом трафик. Каждое число
    объясняется словами: цифра без объяснения заставляет владельца гадать, а гадать он
    просил не заставлять.
    """
    доля_тр = 100.0 * (д['в_месяц_гб'] / 1024.0) / ЛИМ_ТРАФИКА_ТБ
    занято_проц = 100.0 * д['нагрузка'] / max(д['ядер'], 1)
    занято_диск = д['диск_всего'] - д['диск_свободно']

    # ① Из чего исходим. Разделяем «разрешено бесплатно» и «мы себе выделили».
    стр = [
        '🖥 <b>СЕРВЕР ORACLE — сводка</b>', '',
        '<b>① ЧТО ЭТО ЗА МАШИНА</b>',
        'Oracle разрешает бесплатно на весь наш аккаунт: <b>%d ядра, %d ГБ памяти, '
        '%d ГБ диска</b>. Машину заказывали мы сами и размер задавали руками — взяли не всё:'
        % (ЛИМ_ЯДЕР, ЛИМ_ПАМЯТИ_ГБ, ЛИМ_ДИСКА_ГБ),
        '• ядра: <b>%d</b> у машины из %d разрешённых — не взято ещё %d'
        % (д['ядер'], ЛИМ_ЯДЕР, max(ЛИМ_ЯДЕР - д['ядер'], 0)),
        '• память: <b>%.1f ГБ</b> у машины из %d разрешённых — не взято ещё %.1f ГБ'
        % (д['память_всего'], ЛИМ_ПАМЯТИ_ГБ, max(ЛИМ_ПАМЯТИ_ГБ - д['память_всего'], 0)),
        '• диск: <b>%.0f ГБ</b> у машины из %d разрешённых — не взято ещё %.0f ГБ'
        % (д['диск_всего'], ЛИМ_ДИСКА_ГБ, max(ЛИМ_ДИСКА_ГБ - д['диск_всего'], 0)),
        '',
        'То есть <b>%.0f ГБ диска — это не предел Oracle, а наш собственный заказ</b>. '
        'Упрёмся — машине можно добавить, и денег это не стоит: разрешённое не выбрано.'
        % д['диск_всего'],
        '',
        # ② Самочувствие. Здесь числа уже про то, тесно ли машине.
        '<b>② КАК ОНА СЕБЯ ЧУВСТВУЕТ СЕЙЧАС</b>',
        '• работа: ядра заняты на <b>%.0f%%</b> — %s'
        % (занято_проц,
           ('под завязку: больше 100% значит, что задачи стоят в очереди'
            if занято_проц > 95 else
            'плотно, но справляется' if занято_проц > 60 else
            'вполсилы' if занято_проц > 15 else 'почти простаивает')),
        '• память: свободно <b>%.1f ГБ</b> из %.1f — %s'
        % (д['память_свободно'], д['память_всего'],
           ('тесно, новую модель не поднять' if д['память_свободно'] < 1.5 else
            'на одну небольшую модель хватит' if д['память_свободно'] < 4 else 'запас есть')),
        '• диск: занято <b>%.1f ГБ</b>, свободно <b>%.1f ГБ</b> — %s'
        % (занято_диск, д['диск_свободно'],
           ('пора чистить или расширять' if д['диск_свободно'] < 5 else
            'ещё одна модель влезет' if д['диск_свободно'] > 8 else 'место на исходе')),
        '• без перезагрузки работает <b>%s</b>' % _срок(д['часов']),
        '',
        # ③ Трафик — единственное, что считается за месяц и может стоить денег.
        '<b>③ СКОЛЬКО РАЗДАЛИ В ИНТЕРНЕТ</b>',
        'Бесплатно можно отдать <b>10 ТБ в месяц</b> (это 10 240 ГБ). Мы отдали '
        '<b>%.2f ГБ</b> за %s работы; если так пойдёт дальше, за месяц выйдет около '
        '<b>%.0f ГБ</b> — это <b>%.1f%%</b> от разрешённого.'
        % (д['отдано_гб'], _срок(д['часов']), д['в_месяц_гб'], доля_тр),
        '<i>Счёт идёт от последней перезагрузки, а не от первого числа месяца, поэтому '
        'месячная цифра — оценка, а не факт.</i>',
        '',
        '<b>ИТОГ</b>',
    ]

    # Тревоги называем прямо, а не прячем в числах.
    если = []
    if доля_тр > 50:
        если.append('⚠️ трафик перевалил половину разрешённого — стоит посмотреть, что его ест')
    if д['диск_свободно'] < 5:
        если.append('⚠️ на диске меньше 5 ГБ свободного места. Это НЕ предел Oracle: машине '
                    'можно добавить диска бесплатно, разрешённое не выбрано')
    if д['память_свободно'] < 1.5:
        если.append('⚠️ свободной памяти меньше 1,5 ГБ — вторую модель поднимать некуда')
    if занято_проц < 10:
        если.append('ℹ️ процессор загружен меньше 10%: Oracle вправе забрать простаивающую '
                    'машину, если так продержится семь суток подряд')
    стр += если if если else ['✅ всё спокойно: ни одно ограничение даже близко не задето.']
    # Дробная часть через запятую: «11.7 ГБ» — машинное письмо, человек читает «11,7».
    # Точка меняется ТОЛЬКО между цифрами, чтобы не тронуть сокращения и адреса.
    return re.sub(r'(?<=\d)\.(?=\d)', ',', '\n'.join(стр))


def секрет():
    """Ключ к двери уведомлений.

    🔴 04.09.2026. Здесь читался файл `/opt/muslimoon/.backup_secret` — путь я взял с
    ноутбука, где такой файл есть. На СЕРВЕРЕ его нет: там ключ живёт переменной
    BACKUP_SECRET в `.env`, рядом с остальными ключами бота. Сводка исправно считалась и
    молча не отправлялась — «послано владельцу: False» в логе, которого никто не читал.
    Владелец заметил пропажу раньше меня и спросил, где сводки.
    Читаем ОБА места: сперва переменную окружения, потом .env, и только потом файл.
    """
    из_среды = os.environ.get('BACKUP_SECRET')
    if из_среды:
        return из_среды.strip()
    try:
        for с in io.open('/opt/muslimoon/.env', encoding='utf-8', errors='replace'):
            и, _, з = с.partition('=')
            if и.strip() == 'BACKUP_SECRET':
                return з.strip().strip('"').strip("'")
    except Exception:
        pass
    try:
        return io.open(СЕКРЕТ, encoding='utf-8').read().strip()
    except Exception:
        return ''


def послать(текст):
    сек = секрет()
    if not сек:
        print('ключа нет ни в окружении, ни в .env, ни в файле — сводка не отправлена')
        return False
    тело = json.dumps({'secret': сек, 'text': текст}, ensure_ascii=False).encode()
    зап = urllib.request.Request(БАЗА + '/api/claude_notify', data=тело,
                                 headers={'Content-Type': 'application/json'})
    try:
        with urllib.request.urlopen(зап, timeout=60) as о:
            if о.status == 200:
                return True
            print('дверь ответила кодом %s' % о.status)
            return False
    except Exception as е:
        print('дверь не приняла сводку: %s' % str(е)[:200])
        return False


if __name__ == '__main__':
    д = собрать()
    т = словами(д)
    print(т.replace('<b>', '').replace('</b>', '').replace('<i>', '').replace('</i>', ''))
    if '--молча' not in sys.argv:
        print('послано владельцу:', послать(т))
