ПОДОЗРИТЕЛЬНОЕ = ('http://', 'https://', 't.me/', '@', 'wa.me', 'куплю', 'продам',
                  'скидк', 'акци', 'заказ', 'цена', 'руб', 'доллар', 'крипт',
                  'инвест', 'заработок', 'подпишись', 'переходи', 'ставк')


def сейчас():
    return time.strftime('%d.%m.%Y %H:%M')


def журнал_дня():
    return os.path.join(ПАПКА, 'zhurnal-%s.md' % time.strftime('%Y-%m-%d'))


def записать(строка):
    os.makedirs(ПАПКА, exist_ok=True)
    with io.open(журнал_дня(), 'a', encoding='utf-8', newline='\n') as ф:
        ф.write('- %s · %s\n' % (сейчас(), строка))
    print('%s · %s' % (сейчас(), строка), flush=True)


def состояние_взять():
    try:
        return json.load(io.open(СОСТОЯНИЕ, encoding='utf-8'))
    except Exception:
        return {}


def состояние_записать(с):
    os.makedirs(ПАПКА, exist_ok=True)
    врем = СОСТОЯНИЕ + '.новое'
    io.open(врем, 'w', encoding='utf-8', newline='\n').write(
        json.dumps(с, ensure_ascii=False, indent=1))
    os.replace(врем, СОСТОЯНИЕ)


def взять(адрес, тайм=60):
    return urllib.request.urlopen(адрес, timeout=тайм).read().decode('utf-8', 'replace')


def послать(адрес, тело, тайм=180):
    сырое = json.dumps(тело, ensure_ascii=False).encode('utf-8')
    з = urllib.request.Request(адрес, data=сырое,
                               headers={'Content-Type': 'application/json'})
    return json.loads(urllib.request.urlopen(з, timeout=тайм).read().decode('utf-8'))


def спросить_нейронку(указание, вход, начало, сколько=600):
    """Ответ начинаем за неё — иначе Gemma рассуждает вслух и до ответа не доходит."""
    открыть_паузу()
    try:
        промпт = ('<start_of_turn>user\n' + указание + '\n\n' + вход
                  + '<end_of_turn>\n<start_of_turn>model\n' + начало)
        о = послать(МОЗГ, {'prompt': промпт, 'n_predict': сколько, 'temperature': 0.2,
                           'stop': ['<end_of_turn>', '<start_of_turn>', '</end_of_turn>', '</start_of_turn>', '<|im_end|>', '<|im_start|>']}, 600)
        return (начало + (о.get('content') or '')).strip()
    finally:
        закрыть_паузу()


def открыть_паузу():
    try:
        io.open(ПАУЗА, 'w', encoding='utf-8').write(str(int(time.time())))
    except Exception:
        pass


def закрыть_паузу():
    try:
        os.remove(ПАУЗА)
    except Exception:
        pass


def сказать_владельцу(текст):
    """Доклад владельцу через дверь бота. Секрет лежит отдельным файлом на сервере."""
    try:
        сек = io.open(СЕКРЕТ_ФАЙЛ, encoding='utf-8').read().strip()
    except Exception as б:
        записать('❌ не могу прочитать секрет для доклада: %s' % str(б)[:80])
        return False
    try:
        о = послать(БОТ + '/api/skazat',
                    {'secret': сек, 'текст': текст, 'кто': 'сторож',
                     'сессия': 'Сторож на нейронке'}, 240)
        return bool(о.get('пост'))
    except Exception as б:
        записать('❌ доклад не ушёл: %s' % str(б)[:80])
        return False


# ── ① ПРОБА ПРИЛОЖЕНИЯ ────────────────────────────────────────────────────────────────
def проба_приложения(с):
    беды = []
    версия = ''
    try:
        версия = взять(ВИТРИНА + '/ver.txt', 30).strip()[:20]
    except Exception as б:
        беды.append('витрина не отдала версию: %s' % str(б)[:60])
    try:
        з = json.loads(взять(БОТ + '/api/health', 30))
        if not з.get('ok'):
            беды.append('бэкенд отвечает, но не «ok»')
    except Exception as б:
        беды.append('бэкенд не ответил: %s' % str(б)[:60])

    вопрос = random.choice(ВОПРОСЫ_ПРОБЫ)
    try:
        о = послать(БОТ + '/api/rag_find', {'q': вопрос, 'книга': 'все', 'top': 3}, 180)
        найдено = о.get('нашёл') or []
        if not найдено:
            беды.append('поиск ничего не нашёл на «%s» — а ответ в базе есть' % вопрос)
        else:
            первый = найдено[0]
            if not ((первый.get('a') or '').strip() or (первый.get('r') or '').strip()):
                беды.append('поиск вернул пустую запись на «%s»' % вопрос)
    except Exception as б:
        беды.append('поиск не ответил на «%s»: %s' % (вопрос, str(б)[:60]))

    было = с.get('приложение_беды') or []
    if беды:
        записать('🔴 ПРИЛОЖЕНИЕ: ' + ' · '.join(беды))
        if беды != было:                       # о новой беде докладываем сразу
            сказать_владельцу('🔴 Сторож нашёл беду в приложении:\n\n' + '\n'.join(беды)
                              + '\n\nПроверял вопросом «%s», версия витрины %s.'
                              % (вопрос, версия or '?'))
    elif было:
        записать('✅ приложение снова в порядке (версия %s)' % версия)
        сказать_владельцу('✅ Сторож: приложение снова в порядке (версия %s).' % версия)
    с['приложение_беды'] = беды
    с['версия'] = версия
    с['проб_всего'] = (с.get('проб_всего') or 0) + 1
    if not беды:
        с['проб_удачных'] = (с.get('проб_удачных') or 0) + 1
    return с


# ── ② ОШИБКИ БОТА ─────────────────────────────────────────────────────────────────────
def ошибки_бота(с):
    try:
        журнал = json.loads(взять(ДАННЫЕ + '/errors.json', 60))
    except Exception as б:
        записать('журнал ошибок не прочёлся: %s' % str(б)[:70])
        return с
    if not isinstance(журнал, list):
        return с
    видел = set(с.get('видел_ошибки') or [])
    новые = [з for з in журнал
             if з.get('eid') and з['eid'] not in видел and not з.get('fixed')]
    if not новые:
        с['видел_ошибки'] = sorted(видел | {з.get('eid') for з in журнал if з.get('eid')})[-400:]
        return с
    записать('🆕 новых ошибок в журнале: %d' % len(новые))
    for з in новые[-5:]:                       # разбираем не больше пяти за круг
        суть = str(з.get('msg') or з.get('суть') or з.get('text') or '')[:600]
        разбор = ''
        try:
            разбор = спросить_нейронку(
                'Это запись из журнала ошибок нашего бота. Объясни простым языком, '
                'что сломалось и на что это влияет для человека. Две-три строки, по-русски. '
                'Если из записи ничего не понять — так и скажи.',
                суть, 'Простыми словами: ', 180)
        except Exception as б:
            разбор = '(нейронка не ответила: %s)' % str(б)[:60]
        записать('🐞 %s · %s\n    %s' % (з.get('eid'), суть[:160], разбор[:400]))
    с['видел_ошибки'] = sorted(видел | {з.get('eid') for з in журнал if з.get('eid')})[-400:]
    с['ошибок_разобрано'] = (с.get('ошибок_разобрано') or 0) + len(новые[-5:])
    return с


# ── ③ ПЕРЕПИСКА В ЧАТЕ ────────────────────────────────────────────────────────────────
def переписка(с):
    try:
        лента = json.loads(взять(ДАННЫЕ + '/dsoc_lenta.json', 60))
    except Exception as б:
        записать('лента чата не прочлась: %s' % str(б)[:70])
        return с
    if not isinstance(лента, dict):
        return с
    видел = set(с.get('видел_сообщения') or [])
    кандидаты, все_ключи, новых = [], [], []
    for чат, сообщения in лента.items():
        for м in (сообщения or [])[-200:]:
            # 🔴 поля ленты — «i», «кто», «т», и буква «т» здесь КИРИЛЛИЧЕСКАЯ. Сперва я
            # читал 'id' и 't' латиницей: сторож видел пустоту и считался исправным —
            # ровно та беда, ради которой его и ставят. Проверено по живой ленте.
            ключ = '%s:%s' % (чат, м.get('i') or м.get('id') or метка_времени(м))
            все_ключи.append(ключ)
            if ключ in видел:
                continue
            текст = str(м.get('т') or м.get('t') or м.get('текст') or '')
            кто = str(м.get('кто') or м.get('u') or '?')
            новых.append((чат, кто, текст))
            if len(текст) < 12:
                continue
            низ = текст.lower()
            if any(п in низ for п in ПОДОЗРИТЕЛЬНОЕ):
                кандидаты.append((чат, м, текст))
    if новых:
        # владелец просил «сохраняя переписку в течение дня там или больше» — держим
        # свой суточный архив: лента в ветке данных хранит лишь последние 200 на чат
        архив = os.path.join(ПАПКА, 'perepiska-%s.md' % time.strftime('%Y-%m-%d'))
        with io.open(архив, 'a', encoding='utf-8', newline='\n') as ф:
            for чат, кто, текст in новых:
                ф.write('- %s · чат %s · %s: %s\n' % (сейчас(), чат, кто, текст[:500]))
        записать('💬 в переписку добавлено %d сообщений' % len(новых))
    if кандидаты:
        записать('👀 сообщений на проверку: %d (из ленты отобрано дешёвым признаком)'
                 % len(кандидаты))
    сработало = 0
    for чат, м, текст in кандидаты[:6]:        # не больше шести за круг
        try:
            ответ = спросить_нейронку(
                'Это сообщение из чата исламского приложения. Ответь одним словом: '
                'РЕКЛАМА — если это продвижение товара, услуги, канала или заработка; '
                'НАРУШЕНИЕ — если это оскорбление, брань или вражда; '
                'ЧИСТО — если ничего такого нет. После слова добавь короткую причину.',
                текст[:800], 'Ответ: ', 90)
        except Exception:
            continue
        решение = ответ.upper()
        if 'РЕКЛАМА' in решение or 'НАРУШЕНИЕ' in решение:
            сработало += 1
            кто = м.get('кто') or м.get('u') or '?'
            записать('🚩 чат %s · %s · %s\n    сообщение: %s'
                     % (чат, кто, ответ[:160], текст[:200]))
    if сработало:
        сказать_владельцу('🚩 Сторож отметил %d сообщений в чате (реклама или нарушение). '
                          'Подробности в журнале сторожа за сегодня. '
                          'Ничего не удалял и никого не трогал — решение ваше.' % сработало)
    с['видел_сообщения'] = все_ключи[-3000:]
    с['помечено_сообщений'] = (с.get('помечено_сообщений') or 0) + сработало
    return с


def метка_времени(м):
    return str(м.get('d') or м.get('время') or '')[:24]


# ── ④ ОТЧЁТ ВЛАДЕЛЬЦУ ─────────────────────────────────────────────────────────────────
def отчёт(с):
    строки = []
    try:
        строки = io.open(журнал_дня(), encoding='utf-8').read().split('\n')
    except Exception:
        pass
    беды = [с2 for с2 in строки if '🔴' in с2 or '🚩' in с2]
    ошибки = [с2 for с2 in строки if '🐞' in с2]
    всего = с.get('проб_всего') or 0
    удачных = с.get('проб_удачных') or 0
    доля = (100.0 * удачных / всего) if всего else 0
    текст = ('🛡 ОТЧЁТ СТОРОЖА за сутки\n\n'
             'Проверок приложения: %d, из них удачных %d (%.0f%%)\n'
             'Ошибок бота разобрано: %d\n'
             'Сообщений помечено в чате: %d\n'
             % (всего, удачных, доля, с.get('ошибок_разобрано') or 0,
                с.get('помечено_сообщений') or 0))
    if беды:
        текст += '\nЧто нашлось:\n' + '\n'.join(б[:200] for б in беды[:10])
    else:
        текст += '\nЗа сутки бед не нашлось.'
    # 🔴 06.09.2026, вопрос владельца: «можешь отчитываться кто где что тратится?».
    # Может — и пусть приходит САМО, вместе с суточным отчётом, а не по запросу.
    try:
        sys.path.insert(0, '/opt/muslimoon')
        import raskhod_vsego
        текст += '\n\n' + raskhod_vsego.отчёт(кратко=True)
    except Exception as _б:
        текст += '\n\n(отчёт о расходе не собрался: %s)' % str(_б)[:70]
    текст += '\n\nПолный журнал на сервере: %s' % журнал_дня()
    сказать_владельцу(текст)
    записать('📤 отчёт отправлен владельцу')
    for к in ('проб_всего', 'проб_удачных', 'ошибок_разобрано', 'помечено_сообщений'):
        с[к] = 0
    return с


КРУГИ = (('проба', проба_приложения, 600),
         ('ошибки', ошибки_бота, 1800),
         ('переписка', переписка, 1800))


def главная(один_раз=False):
    os.makedirs(ПАПКА, exist_ok=True)
    с = состояние_взять()
    записать('🛡 сторож поднялся')
    if один_раз:
        for имя, дело, _ in КРУГИ:
            try:
                с = дело(с)
            except Exception as б:
                записать('круг «%s» упал: %s' % (имя, str(б)[:120]))
        состояние_записать(с)
        return
    когда = {имя: 0.0 for имя, _д, _с in КРУГИ}
    # 🔴 06.09.2026: отметка «за какой день уже отчитались» жила ТОЛЬКО в памяти процесса.
    # Значит каждый перезапуск сторожа считал, что сегодня ещё не отчитывались, и слал отчёт
    # заново — за один день владелец получил три штуки вместо одного. Держим отметку в
    # состоянии на диске: перезапуск её не сбрасывает.
    отчёт_за = с.get('отчёт_за') or ''
    while True:
        сейчас_сек = time.time()
        for имя, дело, срок in КРУГИ:
            if сейчас_сек - когда[имя] < срок:
                continue
            когда[имя] = сейчас_сек
            try:
                с = дело(с)
            except Exception as б:
                записать('круг «%s» упал: %s' % (имя, str(б)[:120]))
            состояние_записать(с)
        # отчёт раз в сутки в 09:00 по Москве (на сервере UTC, значит 06:00)
        день = time.strftime('%Y-%m-%d')
        if time.strftime('%H:%M') >= '06:00' and отчёт_за != день:
            отчёт_за = день
            try:
                с = отчёт(с)
                с['отчёт_за'] = день
                состояние_записать(с)
            except Exception as б:
                записать('отчёт не собрался: %s' % str(б)[:120])
        time.sleep(60)


if __name__ == '__main__':
    try:
        главная('--раз' in sys.argv)
    except KeyboardInterrupt:
        закрыть_паузу()
