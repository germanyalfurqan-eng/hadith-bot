"""Ответ владельцу в ЕГО чат (Muslimoon-бот, личка) — по З-79: исполнением, не отчётом.

Кто говорит — теперь ПАРАМЕТР, а не константа. Причина: через этот скрипт пишет уже не одна
сессия. Пока имя было зашито, любая другая линия, взяв его в руки, выходила к владельцу под
чужой подписью — а по подписи бот запоминает автора и ему же адресует ответ (реестр авторства,
#269–#278). То есть спрашивал он одного, а слышал другого.
Второго такого скрипта не завожу (З-33): у копии была бы своя дверь, свои умолчания и своё
молчание в тот день, когда они разойдутся с этой.

  python _srochno_otvet.py <файл.txt>                       — как раньше (76 Мини апп)
  python _srochno_otvet.py <файл.txt> <ответ_на>            — как раньше
  python _srochno_otvet.py <файл.txt> --кто "DSOC 1" --сессия "DSOC 1" [--ответ-на 123]
"""
import io, json, os, sys, urllib.request
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')
КОРЕНЬ = os.path.dirname(os.path.abspath(__file__)) or '.'

# Умолчания НЕ трогаю: у 76-й линии команда осталась ровно той же, что была вчера. Правка,
# которая меняет поведение молча, стоит дороже правки, которой нет.
КТО_ПО_УМОЛЧАНИЮ = 'технадзор'
СЕССИЯ_ПО_УМОЛЧАНИЮ = '76 Мини апп'


def послать(текст, ответ_на=None, кто=КТО_ПО_УМОЛЧАНИЮ, сессия=СЕССИЯ_ПО_УМОЛЧАНИЮ):
    сек = io.open(os.path.join(КОРЕНЬ, '.backup_secret'), encoding='utf-8').read().strip()
    тело = {'secret': сек, 'чат': 131827895, 'текст': текст,
            'кто': кто, 'сессия': сессия}
    if ответ_на:
        тело['ответ_на'] = int(ответ_на)
    з = urllib.request.Request(
        'https://melodious-acceptance-production-1c9a.up.railway.app/api/skazat',
        data=json.dumps(тело, ensure_ascii=False).encode(),
        headers={'Content-Type': 'application/json'})
    return json.loads(urllib.request.urlopen(з, timeout=60).read().decode())


def _разобрать(арг):
    """Файл, ответ_на, кто, сессия. Позиционный второй аргумент оставлен ради старых вызовов."""
    файл, ответ_на = арг[0], None
    кто, сессия = КТО_ПО_УМОЛЧАНИЮ, СЕССИЯ_ПО_УМОЛЧАНИЮ
    ост = арг[1:]
    if ост and not ост[0].startswith('--'):
        ответ_на, ост = ост[0], ост[1:]
    i = 0
    while i < len(ост):
        имя, зн = ост[i], (ост[i + 1] if i + 1 < len(ост) else '')
        if имя == '--кто':
            кто = зн
        elif имя == '--сессия':
            сессия = зн
        elif имя in ('--ответ-на', '--ответ_на'):
            ответ_на = зн
        else:
            raise SystemExit('не знаю ключа «%s». Есть: --кто, --сессия, --ответ-на' % имя)
        i += 2
    return файл, ответ_на, кто, сессия


if __name__ == '__main__':
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    ф, о, к, с = _разобрать(sys.argv[1:])
    т = io.open(ф, encoding='utf-8').read()
    print(json.dumps(послать(т, о, к, с), ensure_ascii=False))
