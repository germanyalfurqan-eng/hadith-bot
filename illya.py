def _шарды(вид, bid):
    """Все шарды одного сборника: {номер: запись}."""
    из = {}
    for f in glob.glob(os.path.join(М, вид, ('b%s_*.json' if вид == 'dz' else '%s_*.json') % bid)):
        try:
            из.update(json.load(io.open(f, encoding='utf-8')))
        except Exception:
            pass
    return из


_РАВИИ = None


def равии():
    """id → {name, death, hajar, dhahabi, jarh}. Читается один раз."""
    global _РАВИИ
    if _РАВИИ is not None:
        return _РАВИИ
    j = json.load(io.open(os.path.join(М, 'narrators_index.json'), encoding='utf-8'))
    к = j['cols']
    и = {им: к.index(им) for им in к}
    _РАВИИ = {}
    for с in j['data']:
        _РАВИИ[str(с[и['id']])] = {
            'имя': с[и['name']] or '', 'смерть': с[и['death']] or '',
            'хаджар': с[и['rankHajar']] or '', 'захаби': с[и['rankDhahabi']] or '',
            'джарх': с[и['jarh']] or ''}
    return _РАВИИ


def флаги(р):
    """Тревожные слова критиков об этом равии — с цитатой, а не пересказом."""
    поле = ' '.join([р.get('хаджар', ''), р.get('захаби', ''), р.get('джарх', '')])
    из = []
    for шаб, что, вес in ФЛАГИ:
        m = re.search(шаб, поле)
        if m:
            н, к = max(0, m.start() - 40), min(len(поле), m.end() + 40)
            из.append((вес, что, поле[н:к].strip()))
    из.sort(key=lambda x: -x[0])
    видел, чисто = set(), []
    for в, ч, ц in из:
        if ч in видел:
            continue
        видел.add(ч)
        чисто.append((в, ч, ц))
    return чисто


