def остов(s):
    """Арабский без огласовок и с приведёнными буквами — чтобы сравнивать смысл,
    а не разметку. Тот же приём, что в build_verify_discrepancy.skel."""
    из = []
    for c in str(s or ''):
        o = ord(c)
        if 0x064B <= o <= 0x0652 or o == 0x0670 or c in 'ـ"‏':
            continue
        из.append(c)
    t = ''.join(из)
    for a, b in [('أ', 'ا'), ('إ', 'ا'), ('آ', 'ا'), ('ى', 'ي'), ('ة', 'ه')]:
        t = t.replace(a, b)
    return re.sub(r'\s+', ' ', t).strip()


def похожесть(a, b):
    from difflib import SequenceMatcher
    # autojunk=False обязателен: иначе частые арабские буквы выкидываются
    # и сходство занижается (тех. заметка проекта, грабли многократные)
    return SequenceMatcher(None, a, b, autojunk=False).ratio()


def пути(bid, номер, порог=0.45, шире=True):
    """Пути (طرق) ОДНОГО сообщения: тот же сподвижник И близкий матн.

    🔴 Первая моя попытка брала только сподвижника — и выдала 2375 «путей»
    для Бухари 391. Это не пути одного хадиса, а всё, что Анас передал за жизнь.
    Пути — это пути одного МАТНА; без сравнения текста получается не разбор,
    а свалка, в которой настоящий дефект тонет.
    """
    цепи = _шарды('dz', bid)
    свой = цепи.get(str(номер))
    if not свой or not свой.get('s'):
        return None, []
    сп = [str(x) for x in свой['s']][-1]
    свой_т = остов(тексты(bid).get(str(номер), ''))
    найдено = [(bid, str(номер), [str(x) for x in свой['s']], 1.0)]
    for б in (list(СБОРНИКИ) if шире else [bid]):
        ц = цепи if б == bid else _шарды('dz', б)
        тб = тексты(б)
        for н, зап in ц.items():
            if б == bid and н == str(номер):
                continue
            s = [str(x) for x in (зап.get('s') or [])]
            if not s or s[-1] != сп:
                continue
            п = похожесть(свой_т, остов(тб.get(н, ''))) if свой_т else 0
            if п >= порог:
                найдено.append((б, н, s, п))
    найдено.sort(key=lambda x: -x[3])
    return сп, найдено


def скрытые_звенья(bid, номер, цепь, круг=None):
    """Равии, названные В ТЕКСТЕ, но отсутствующие в иснаде.

    🔴 Ради этого всё и затевалось. Бухари 393: иснад идёт «Халид ← Хумайд ← Анас»,
    а в матне стоит «سأل ميمون بن سياه أنس بن مالك» — спрашивал Маймун ибн Сийях.
    По цепям это НЕВИДИМО: Маймуна в иснаде нет. А значит путь, который выглядит
    независимым подкреплением, на деле возвращается к тому же самому человеку.
    Это и есть скрытый дефект — он потому и скрытый, что не в иснаде.
    """
    т = остов(тексты(bid).get(str(номер), ''))
    if not т:
        return []
    р = равии()
    в_цепи = set(цепь)
    сп = цепь[-1] if цепь else None
    имя_сп = остов((р.get(сп, {}).get('имя') or '').split(' بن ')[0]) if сп else ''
    из = []
    for i in (круг or ()):
        if i in в_цепи:
            continue
        зап = р.get(i) or {}
        части = (зап.get('имя') or '').split(' بن ')
        if len(части) < 2:
            continue
        шаб = остов(части[0] + ' بن ' + части[1].split(' ')[0])
        # 🔴 без этих двух условий механизм ловил ТЁЗОК: на один текст выпадало
        # двадцать разных «Хафс ибн Умар», и настоящая находка тонула в них.
        # Имя, совпавшее буква в букву, — ещё не тот человек.
        if len(шаб) < 10 or шаб not in т:
            continue
        if имя_сп and шаб.startswith(имя_сп):
            continue                      # это сам сподвижник под другим id
        # 🔴 Второй источник шума: текст хадиса содержит и САМ ИСНАД, поэтому имена
        # звеньев в нём есть всегда. Различаем по слову ПЕРЕД именем: если это
        # иснадная связка (حدثنا / عن / أخبرنا…), человек стоит в цепи — не находка.
        # Находка — когда он назван как действующее лицо: «سأل ميمون بن سياه أنسا».
        до = т[:т.index(шаб)].split()
        связка = до[-1] if до else ''
        if связка in СВЯЗКИ:
            continue
        из.append((i, зап.get('имя', '')[:40], связка))
    return из


# Слова, которыми в иснаде соединяют звенья. Имя после них — звено цепи, а не
# действующее лицо рассказа.
СВЯЗКИ = {'حدثنا', 'حدثني', 'اخبرنا', 'اخبرني', 'انبانا', 'ثنا', 'نا', 'عن', 'سمعت',
          'حدثه', 'اخبره', 'وحدثنا', 'وحدثني', 'واخبرنا', 'وعن', 'قال', 'وقال'}


def мадар(пути_):
    """Звено, через которое проходят ВСЕ пути и которое стоит выше сподвижника.

    Ниже мадара цепи общие, выше — расходятся. Если мадар только сподвижник,
    значит пути правда независимы, и это укрепляет сообщение.
    """
    наборы = [set(s) for _, _, s in пути_]
    общие = set.intersection(*наборы) if наборы else set()
    сп = пути_[0][2][-1] if пути_ else None
    порядок = [x for x in пути_[0][2] if x in общие]
    выше = [x for x in порядок if x != сп]
    return (выше[-1] if выше else сп), общие


def разбор(bid, номер, шире=True):
    bid = ПО_ИМЕНИ.get(str(bid).lower(), str(bid))
    сп, найд = пути(bid, номер, шире=шире)
    if сп is None:
        return {'ошибка': 'нет такого номера в %s' % СБОРНИКИ.get(bid, bid)}
    р = равии()
    м, общие = мадар([(б, н, s) for б, н, s, _ in найд])
    свой = найд[0][2]
    расх = [x for x in свой if x not in общие]
    # 🔴 Круг кандидатов — НЕ участники найденных путей. Первый раз я собрал его
    # именно так, и он отсёк Маймуна ибн Сийяха: в путях 393 его нет — он там и
    # спрятан. Сужение убило ровно то, ради чего всё затевалось. Круг = все, кто
    # вообще передаёт от этого сподвижника, по всем сборникам.
    круг = set()
    for б in СБОРНИКИ:
        for _н, зап in _шарды('dz', б).items():
            s_ = [str(x) for x in (зап.get('s') or [])]
            if s_ and s_[-1] == сп:
                круг.update(s_)
    ученики, скрытые = {}, {}
    for б, н, s, п in найд:
        if len(s) >= 2:
            ученики.setdefault(s[-2], []).append('%s %s' % (СБОРНИКИ.get(б, б), н))
        сз = скрытые_звенья(б, н, s, круг)
        if сз:
            скрытые['%s %s' % (СБОРНИКИ.get(б, б), н)] = сз
    return {'bid': bid, 'сборник': СБОРНИКИ.get(bid, bid), 'номер': str(номер),
            'сподвижник': сп, 'путей': len(найд), 'мадар': м,
            'своя': свой, 'расхождение': расх, 'ученики': ученики,
            'скрытые': скрытые, 'пути': найд, 'равии': р}


def отчёт(d, максПутей=12):
    if 'ошибка' in d:
        return '❌ ' + d['ошибка']
    р = d['равии']

    def имя(i):
        return (р.get(i, {}).get('имя') or ('id ' + i)).split(' بن ')[0][:34]

    L = []
    L.append('🔍 ИЛЛЯ · %s %s — сведение путей' % (d['сборник'], d['номер']))
    L.append('')
    L.append('Сподвижник: %s (id %s) · путей от него найдено: %d'
             % (имя(d['сподвижник']), d['сподвижник'], d['путей']))
    L.append('Своя цепь: ' + ' ← '.join(имя(i) for i in d['своя']))
    L.append('')

    if d['мадар'] and d['мадар'] != d['сподвижник']:
        L.append('📍 МАДАР (точка вращения): %s — через него проходят ВСЕ пути.'
                 % имя(d['мадар']))
        L.append('   Значит пути НЕ независимы: дефект этого звена бьёт по всем сразу.')
    else:
        L.append('📍 Мадар — сам сподвижник: выше него пути расходятся, то есть они '
                 'независимы. Это сообщение УКРЕПЛЯЕТ, а не ослабляет.')
    L.append('')

    if d.get('скрытые'):
        L.append('🔴 СКРЫТОЕ ЗВЕНО — в тексте назван передатчик, которого НЕТ в иснаде:')
        for где, кто in d['скрытые'].items():
            for i, им, св in кто:
                L.append('   • %s: назван «%s» (id %s), перед именем — «%s»'
                         % (где, им, i, св))
                ф = флаги(р.get(i, {}))
                for в, ч, ц in ф[:2]:
                    L.append('       %s %s — «%s»' % ('🔴' if в >= 3 else '🟡', ч, ц[:100]))
        L.append('   ⚠️ Путь, выглядящий независимым подкреплением, может возвращаться')
        L.append('      к тому же человеку. По одним цепям это не видно.')
        L.append('')

    if len(d['ученики']) > 1:
        L.append('🔀 От сподвижника передают разные ученики — вот где сверять:')
        for уч, где in sorted(d['ученики'].items(), key=lambda x: -len(x[1])):
            свои = флаги(р.get(уч, {}))
            метка = ('  ⚠️ ' + '; '.join(ч for _, ч, _ in свои[:2])) if свои else '  ✅ упрёков нет'
            L.append('   • %-34s путей %d%s' % (имя(уч), len(где), метка))
            L.append('     %s' % ', '.join(где[:6]) + (' …' if len(где) > 6 else ''))
        L.append('')

    L.append('⚖️ ЧТО СКАЗАЛИ КРИТИКИ О ЗВЕНЬЯХ ЭТОЙ ЦЕПИ:')
    for i in d['своя']:
        зап = р.get(i, {})
        ф = флаги(зап)
        стр = '   %-34s' % имя(i)
        оц = (зап.get('хаджар') or зап.get('захаби') or '').strip()
        if оц:
            стр += ' · ' + оц[:60]
        L.append(стр)
        for в, ч, ц in ф[:3]:
            L.append('       %s %s — «%s»' % ('🔴' if в >= 3 else '🟡', ч, ц[:110]))
        if not ф and not оц:
            L.append('       нет данных об оценке')
    L.append('')
    L.append('ℹ️ Это материал для суждения, а не хукм. Хукм выносит владелец/учёные.')
    return '\n'.join(L)


