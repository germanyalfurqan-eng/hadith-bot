"""МОЖНО ЛИ ВЫКАТЫВАТЬ ПРЯМО СЕЙЧАС — спросить ПЕРЕД каждым git push боевого bot.py.

🔴 ЗАЧЕМ. За одну ночь 20.08.2026 выкатка дважды съела вопрос владельца. Оба раза одинаково:
он спрашивал помощника, местная модель на его ноутбуке честно считала минуту-другую, а сервер
в это время перезапускался деплоем — и вернувшийся ответ упирался в «задание истекло». Со
стороны владельца это выглядело как «бот молчит», и второй раз я угробил его вопрос ровно тем,
что спешил отдать ему починку.

Обещание «не буду выкатывать, пока он разговаривает» я дал и нарушил через двадцать минут.
Обещание забыть можно, проверку — нет. Поэтому проверка, а не намерение.

ЧТО СМОТРИТ:
  ① занята ли местная модель прямо сейчас (в журнале работника «ВЗЯЛ» без парного «отдал»);
  ② как давно работник вообще что-то делал — если минуту назад, разговор идёт, и выкатка
     оборвёт следующий же вопрос;
  ③ жив ли сам работник, иначе «тихо» означает не «свободно», а «некому работать».

Запуск:  python mozhno_vykatyvat.py
Код возврата 0 — можно, 1 — нельзя (годится для `python mozhno_vykatyvat.py && git push`).
"""
import io
import os
import re
import subprocess
import sys
import time

КОРЕНЬ = os.path.dirname(os.path.abspath(__file__)) or '.'
ЖУРНАЛ = os.path.join(КОРЕНЬ, 'rabotnik_lokalok.log')
ТИХО_НАДО = 180        # сек: столько тишины считаем «разговор закончился»


def _строки():
    try:
        with io.open(ЖУРНАЛ, encoding='utf-8', errors='replace') as ф:
            return ф.read().splitlines()[-400:]
    except Exception:
        return []


def _время(строка):
    """«20.08 01:01:44 · …» → отметка времени сегодняшнего дня, либо None."""
    м = re.match(r'(\d{2})\.(\d{2}) (\d{2}):(\d{2}):(\d{2})', строка or '')
    if not м:
        return None
    д, мес, ч, мин, с = (int(x) for x in м.groups())
    т = time.localtime()
    try:
        return time.mktime((т.tm_year, мес, д, ч, мин, с, 0, 0, -1))
    except Exception:
        return None


def _работник_жив():
    try:
        о = subprocess.run(
            ['powershell', '-NoProfile', '-Command',
             "(Get-CimInstance Win32_Process -Filter \"Name like '%python%'\" | "
             "Where-Object { $_.CommandLine -like '*rabotnik_lokalok*' } | "
             "Measure-Object).Count"],
            capture_output=True, text=True, timeout=25)
        return (о.stdout or '0').strip().isdigit() and int((о.stdout or '0').strip()) > 0
    except Exception:
        return None            # не выяснили — так и скажем, а не соврём «жив»


def разбор():
    строки = _строки()
    беды, замечания = [], []

    жив = _работник_жив()
    if жив is False:
        замечания.append('работник на ноутбуке НЕ ЗАПУЩЕН — тишина в журнале ничего не значит')
    elif жив is None:
        замечания.append('жив ли работник — выяснить не вышло')

    if not строки:
        замечания.append('журнала работника нет или он пуст — судить не по чему')
        return беды, замечания

    # ① незакрытое «ВЗЯЛ»: работа сейчас на руках у модели.
    # ⚠️ Считаем по НОМЕРУ СТРОКИ, а не через .index(): index находит ПЕРВОЕ вхождение, а
    # строки журнала повторяются дословно («РАБОТНИК-ЖИВ…»). Первая же версия этой проверки
    # сравнивала номера чужих строк и врала бы — поймано до первого запуска.
    и_взял = и_отдал = -1
    последний_взял = None
    for н, с in enumerate(строки):
        if 'ВЗЯЛ ' in с:
            и_взял, последний_взял = н, с
        elif '✓ отдал' in с or '✗ модель не ответила' in с:
            и_отдал = н
    if последний_взял and и_взял > и_отдал:
        т = _время(последний_взял)
        сколько = int(time.time() - т) if т else -1
        беды.append('МОДЕЛЬ СЕЙЧАС СЧИТАЕТ (взяла %s назад) — выкатка убьёт этот ответ:\n    %s'
                    % (('%d с' % сколько) if сколько >= 0 else 'недавно', последний_взял.strip()))

    # ② давно ли вообще работали
    свежие = [_время(с) for с in строки if ('ВЗЯЛ ' in с or '✓ отдал' in с)]
    свежие = [т for т in свежие if т]
    if свежие:
        молчит = int(time.time() - max(свежие))
        if молчит < ТИХО_НАДО:
            беды.append('разговор с помощником идёт: последняя работа %d с назад '
                        '(тишины надо хотя бы %d с)' % (молчит, ТИХО_НАДО))
        else:
            замечания.append('тихо уже %d с — похоже, разговор закончился' % молчит)
    return беды, замечания


if __name__ == '__main__':
    try:
        sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')
    except Exception:
        pass
    беды, замечания = разбор()
    for з in замечания:
        print('   · %s' % з)
    if беды:
        print()
        print('🔴 ВЫКАТЫВАТЬ НЕЛЬЗЯ:')
        for б in беды:
            print('   %s' % б)
        print()
        print('   Подожди тишины либо спроси владельца прямо. Съеденный его вопрос стоит')
        print('   дороже, чем починка, которая полежит десять минут.')
        raise SystemExit(1)
    print()
    print('✅ можно выкатывать: модель свободна, разговор не идёт')
