def счёт_за_месяц(конфиг):
    """Сколько Oracle НАСЧИТАЛА за текущий месяц. Ноль — то, ради чего всё это.

    Спрашиваем у самой Oracle, а не считаем сами: наш расчёт может ошибаться, счёт — нет.
    """
    try:
        # 🔴 Первый заход вернул 400 InvalidParameter: я передал время «как сейчас», с
        # часами и минутами. Usage API принимает только ГРАНИЦЫ СУТОК в UTC — иначе
        # отказ, и сторож остался бы без своей главной проверки.
        сейчас = datetime.datetime.now(datetime.timezone.utc)
        начало = datetime.datetime(сейчас.year, сейчас.month, 1,
                                   tzinfo=datetime.timezone.utc)
        конец = datetime.datetime(сейчас.year, сейчас.month, сейчас.day,
                                  tzinfo=datetime.timezone.utc) + datetime.timedelta(days=1)
        клиент = oci.usage_api.UsageapiClient(конфиг)
        о = клиент.request_summarized_usages(
            oci.usage_api.models.RequestSummarizedUsagesDetails(
                tenant_id=ОТСЕК, granularity='DAILY', query_type='COST',
                time_usage_started=начало, time_usage_ended=конец))
        сумма = 0.0
        валюта = ''
        for э in (о.data.items or []):
            сумма += float(getattr(э, 'computed_amount', 0) or 0)
            валюта = getattr(э, 'currency', '') or валюта
        return {'сумма': round(сумма, 4), 'валюта': валюта or 'USD', 'спрошено': True}
    except Exception as б:
        return {'сумма': None, 'валюта': '', 'спрошено': False, 'почему': str(б)[:160]}


