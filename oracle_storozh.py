def часов_в_месяце():
    """Сколько часов в текущем месяце и сколько из них уже прошло."""
    сейчас = datetime.datetime.now(datetime.timezone.utc)
    дней = calendar.monthrange(сейчас.year, сейчас.month)[1]
    всего = дней * 24
    прошло = (сейчас.day - 1) * 24 + сейчас.hour + сейчас.minute / 60.0
    return всего, прошло


def часов_машины(создана):
    """Сколько часов машина отработала В ЭТОМ МЕСЯЦЕ — то есть сколько уже СЪЕДЕНО.

    Считаем от начала месяца либо от рождения машины, смотря что позже: за дни, когда её
    ещё не было, часы не начисляются.
    """
    сейчас = datetime.datetime.now(datetime.timezone.utc)
    нач = datetime.datetime(сейчас.year, сейчас.month, 1, tzinfo=datetime.timezone.utc)
    старт = нач
    try:
        if создана is not None:
            с = создана
            if с.tzinfo is None:
                с = с.replace(tzinfo=datetime.timezone.utc)
            старт = max(нач, с)
    except Exception:
        старт = нач
    return max(0.0, (сейчас - старт).total_seconds() / 3600.0)


